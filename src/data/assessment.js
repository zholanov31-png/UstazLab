// Жауаптардан әр құзырет бойынша 0–100 балл есептейді
export function scoreAssessment(answers) {
  const totals = {};
  const maxes = {};
  for (const item of assessmentItems) {
    const max = Math.max(...item.options.map((o) => o.score));
    const chosen = item.options.find((o) => o.id === answers[item.id]);
    totals[item.competency] = (totals[item.competency] || 0) + (chosen ? chosen.score : 0);
    maxes[item.competency] = (maxes[item.competency] || 0) + max;
  }
  const scores = {};
  for (const key of Object.keys(maxes)) {
    scores[key] = Math.round((totals[key] / maxes[key]) * 100);
  }
  return scores;
}
